    #[test]
    fn vip_contacts_and_missing_messages() {
        let (store, mut settings, inbox) = setup();
        store.set_vip(&Address::new("Very Important", "vip@example.net"), true).unwrap();
        let id = insert(&store, inbox, "Very Important <vip@example.net>", "Hi", "");
        settings.rules.push(rule(
            "vip",
            vec![cond(Field::SenderIsVip, Op::Contains, ""), cond(Field::SenderInContacts, Op::Contains, ""), cond(Field::Account, Op::Is, "Work")],
            vec![RuleAction::SetColor { color: FlagColor::Purple }],
        ));
        let effects = apply_rules(&store, &settings, &[id, 999_999], None);
        assert_eq!(store.message(id).unwrap().color, Some(FlagColor::Purple));
        assert!(matches!(effects.last(), Some(SideEffect::Changed)));
        assert!(apply_rules(&store, &Settings::default(), &[id], None).is_empty());
    }
