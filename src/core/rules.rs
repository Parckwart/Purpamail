//! Mail rules engine.
//!
//! Rules are evaluated in order. For every message, each enabled rule whose
//! [`Criteria`](super::criteria::Criteria) match has its actions performed in
//! order through [`super::ops`], so that changes are queued for the server.
//! `Stop Evaluating Rules` ends rule processing for the message, and so does
//! moving or deleting it: the remaining actions of the rule that moved the
//! message still run (e.g. "move to Receipts and mark as read"), later rules do
//! not. Actions that need the outside world — sending a reply / forward /
//! redirect, playing a sound, showing a notification, running a command — are
//! returned as [`SideEffect`]s for the caller to execute.

